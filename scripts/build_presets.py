"""Bundle labels/*.json into app_study/static/presets.js.

The page loads label sets from presets.js (a plain script) so that the bundled
presets also work when index.html is opened straight from disk, where the
browser does not allow fetching JSON files.

Usage:
    python scripts/build_presets.py          # rewrite presets.js
    python scripts/build_presets.py --check  # exit 1 if presets.js is out of date
"""
import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
LABELS_DIR = os.path.join(ROOT, "labels")
OUTPUT = os.path.join(ROOT, "app_study", "static", "presets.js")
DEFAULT_PRESET = "s-iase"


def build():
    presets = {}
    for name in sorted(os.listdir(LABELS_DIR)):
        if name.endswith(".json"):
            with open(os.path.join(LABELS_DIR, name), encoding="utf-8") as f:
                presets[name[: -len(".json")]] = json.load(f)
    if DEFAULT_PRESET not in presets:
        raise SystemExit(f"labels/{DEFAULT_PRESET}.json is missing")
    body = json.dumps(presets, indent=4, ensure_ascii=False).replace("\n", "\n    ")
    lines = [
        "// Generated by scripts/build_presets.py from labels/*.json. Do not edit by hand.",
        "(function (root) {",
        f"    var presets = {body};",
        f"    var api = {{ defaultId: {json.dumps(DEFAULT_PRESET)}, presets: presets }};",
        "    if (typeof module === \"object\" && module.exports) {",
        "        module.exports = api;",
        "    } else {",
        "        root.DSTPresets = api;",
        "    }",
        "})(typeof self !== \"undefined\" ? self : this);",
    ]
    return "\n".join(lines) + "\n"


def main():
    content = build()
    if "--check" in sys.argv:
        try:
            with open(OUTPUT, encoding="utf-8") as f:
                current = f.read()
        except FileNotFoundError:
            current = ""
        if current != content:
            print("app_study/static/presets.js is out of date; run: python scripts/build_presets.py")
            sys.exit(1)
        print("presets.js is up to date")
        return
    with open(OUTPUT, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"wrote {os.path.relpath(OUTPUT, ROOT)}")


if __name__ == "__main__":
    main()
